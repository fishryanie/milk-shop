"""Rebuild small Latin/Vietnamese fonts with full-font Unicode fallbacks.

Run: uv run --with fonttools --with brotli python scripts/optimize-fonts.py
The original fonts and their licenses remain in public/fonts/.
"""

from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont


directory = Path(__file__).resolve().parent.parent / "public" / "fonts"
common = set(range(0x20, 0x100)) | set(range(0x300, 0x370)) | set(range(0x1E00, 0x1F00)) | set(range(0x2000, 0x2070)) | {
    0x102, 0x103, 0x110, 0x111, 0x128, 0x129, 0x168, 0x169,
    0x1A0, 0x1A1, 0x1AF, 0x1B0, 0x20AB,
}


def unicode_ranges(points):
    runs = []
    for point in sorted(points):
        if runs and point == runs[-1][1] + 1:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ",".join(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}" for start, end in runs)


fallbacks = ["/* Generated by scripts/optimize-fonts.py. Full originals cover uncommon glyphs. */"]
for name in ["be-vietnam-regular", "be-vietnam-semibold", "dm-serif"]:
    source = directory / f"{name}.woff2"
    target = directory / f"{name}-optimized.woff2"
    font = TTFont(source)
    characters = font.getBestCmap()
    options = subset.Options()
    # Retain outlines, kerning and shaping for Latin and Vietnamese. Remove TrueType
    # hint programs; modern antialiasing does not need their network overhead.
    options.hinting = False
    options.layout_features = ["*"]
    optimizer = subset.Subsetter(options=options)
    optimizer.populate(unicodes=characters.keys() & common)
    optimizer.subset(font)
    font.flavor = "woff2"
    font.save(target)
    included = TTFont(target).getBestCmap().keys()
    remaining = characters.keys() - included
    assert included == characters.keys() & common
    assert included | remaining == characters.keys()
    if remaining:
        family = "DM Serif Full" if name == "dm-serif" else "Be Vietnam Full"
        weight = "600 800" if name.endswith("semibold") else "400"
        fallbacks.append(f'@font-face {{ font-family: "{family}"; src: url("/fonts/{name}.woff2") format("woff2"); font-weight: {weight}; font-style: normal; font-display: swap; unicode-range: {unicode_ranges(remaining)}; }}')
    print(f"{target.name}: {source.stat().st_size:,} → {target.stat().st_size:,} bytes")

(directory / "fallbacks.css").write_text("\n".join(fallbacks) + "\n")
